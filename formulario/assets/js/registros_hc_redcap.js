        /**
         * Normaliza o valor digitado do HC removendo pontuações e convertendo para maiúsculas
         */
        normalizar: function(valor) {
            if (!valor) return '';
            return String(valor).replace(/[^a-zA-Z0-9]/g, '').toUpperCase().trim();
        },

        /**
         * Verifica se o registro HC já existe no REDCap
         * @param {string} hc - Número ou código do prontuário
         * @returns {object|null} Objeto com dados do paciente existente ou null
         */
        buscar: function(hc) {
            const limpo = this.normalizar(hc);
            if (!limpo || limpo.length < 3) return null;

            const base = window.REGISTROS_HC_REDCAP || {};

            // 1. Busca exata
            if (base[limpo]) {
                return base[limpo];
            }

            // 2. Se digitado com 7 caracteres (ex: sem o zero inicial), tenta preencher com zero à esquerda
            if (limpo.length === 7) {
                const comZero = '0' + limpo;
                if (base[comZero]) return base[comZero];
            }

            // 3. Se digitado com 8 caracteres começando com zero, tenta sem o zero
            if (limpo.length === 8 && limpo.startsWith('0')) {
                const semZero = limpo.substring(1);
                if (base[semZero]) return base[semZero];
            }

            return null;
        }
